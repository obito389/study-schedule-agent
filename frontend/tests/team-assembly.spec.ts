import { test, expect } from '@playwright/test'

test('成员前端串通任务、预览确认、撤销、反馈、导入和偏好', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', e => errors.push(e.message))
  await page.goto('/tasks')
  await expect(page.getByText('学习日程 Agent · 团队版')).toBeVisible()
  await page.getByRole('button', { name: '新建任务', exact: true }).click()
  const dialog=page.getByRole('dialog')
  const title='团队端到端任务 '+Date.now()
  await dialog.locator('input').first().fill(title)
  await dialog.getByRole('button', {name:'确认保存任务'}).click()
  await expect(page.getByRole('row').filter({hasText:title})).toBeVisible()
  await page.getByRole('menuitem',{name:'日程日历'}).click()
  await page.getByRole('button',{name:'规则排程',exact:true}).click()
  await expect(page.getByRole('dialog')).toContainText('待确认')
  await page.getByRole('button',{name:'确认执行',exact:true}).click()
  await expect(page.getByRole('button',{name:'撤销此操作'})).toBeVisible()
  await page.getByRole('button',{name:'撤销此操作'}).click()
  await expect(page.getByRole('dialog')).toBeHidden()
  await page.getByRole('button',{name:'规则排程',exact:true}).click()
  await page.getByRole('button',{name:'确认执行',exact:true}).click()
  await page.getByRole('button',{name:'关闭',exact:true}).click()
  await expect(page.locator('.fc-event').filter({hasText:title}).first()).toBeVisible()
  const snapshot=await (await page.request.get('/api/v1/schedule/snapshot',{headers:{'X-User-Id':'1'}})).json()
  const planned=snapshot.data.tasks.find((t:{title:string})=>t.title===title)
  expect(planned.scheduledBlocks.reduce((sum:number,b:{start:string;end:string})=>sum+(Date.parse(b.end)-Date.parse(b.start))/60000,0)).toBe(60)
  await page.getByRole('menuitem',{name:'任务管理'}).click()
  await page.getByRole('row').filter({hasText:title}).getByRole('button',{name:'完成并反馈'}).click()
  await page.locator('.el-message-box input').fill('90')
  await page.getByRole('button',{name:'确认完成',exact:true}).click()
  await expect(page.getByRole('row').filter({hasText:title})).toContainText('已完成')
  await page.getByRole('menuitem',{name:'用户事实'}).click()
  await expect(page.getByText('duration.sample.',{exact:false}).first()).toBeVisible()
  await page.getByRole('spinbutton').first().fill('300')
  await page.getByRole('button',{name:'确认设置上限'}).click()
  await expect(page.getByText('已保存',{exact:true})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('spinbutton').first()).toHaveValue('300')
  await page.getByRole('menuitem',{name:'导入与校对'}).click()
  await page.locator('.el-select').click()
  await page.getByRole('option',{name:'截图或图片'}).click()
  await page.getByLabel('选择导入文件').setInputFiles({name:'assignment.png',mimeType:'image/png',buffer:Buffer.from([1,2,3])})
  await page.getByRole('button',{name:'上传并生成提案'}).click()
  await expect(page.getByText('截图导入待核对',{exact:true})).toHaveCount(0)
  await expect(page.locator('.el-col').last().locator('input').first()).toHaveValue('截图导入待核对')
  const imported='团队导入任务 '+Date.now()
  await page.locator('.el-col').last().locator('input').first().fill(imported)
  await page.getByRole('button',{name:'已核对，确认创建任务'}).click()
  await expect(page.getByText('任务已保存',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'查看任务'}).click()
  await expect(page.getByRole('row').filter({hasText:imported})).toBeVisible()
  expect(errors).toEqual([])
})

test('课程和固定时段使用成员实体并出现在日历',async({page})=>{
  await page.goto('/')
  await page.getByRole('button',{name:'课程 / 固定时段'}).click()
  const dialog=page.getByRole('dialog')
  const title='团队课程 '+Date.now()
  await dialog.locator('input[type=text]').first().fill(title)
  await dialog.getByRole('button',{name:'确认添加'}).click()
  await expect(dialog.getByText(title,{exact:true})).toBeVisible()
  await dialog.locator('.entry').filter({hasText:title}).getByRole('button',{name:'删除'}).click()
  await page.getByRole('button',{name:'确定',exact:true}).click()
  await expect(dialog.getByText(title,{exact:true})).toBeHidden()
})
